  function validateArticles(list) {
    if (!Array.isArray(list) || list.length !== 20) {
      throw new Error("يجب أن يحتوي الملف على 20 مقالًا بالضبط.");
    }

    const ids = new Set();

    for (const article of list) {
      if (!article.id || ids.has(article.id)) {
        throw new Error("يوجد معرف مقال مفقود أو مكرر.");
      }

      ids.add(article.id);

      if (
        !article.title ||
        !article.description ||
        !article.category ||
        !article.cover ||
        !Array.isArray(article.tags) ||
        !Array.isArray(article.content) ||
        article.content.length < 4
      ) {
        throw new Error("بيانات أحد المقالات غير مكتملة: " + article.id);
      }

      for (const section of article.content) {
        if (
          !section.heading ||
          !Array.isArray(section.paragraphs) ||
          section.paragraphs.length === 0 ||
          section.paragraphs.some(function (paragraph) {
            return typeof paragraph !== "string" || !paragraph.trim();
          })
        ) {
          throw new Error("قسم غير مكتمل في المقال: " + article.id);
        }
      }
    }
  }

  validateArticles(articles);

  if (typeof window !== "undefined") {
    window.HANOON_ARTICLES_DEVELOPMENT = articles;

    if (typeof window.HANOON_REGISTER_ARTICLES === "function") {
      window.HANOON_REGISTER_ARTICLES(articles);
    } else {
      window.addEventListener("hanoon:articles-ready", function () {
        if (typeof window.HANOON_REGISTER_ARTICLES === "function") {
          window.HANOON_REGISTER_ARTICLES(articles);
        }
      }, { once: true });
    }
  }
