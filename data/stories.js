  function validateStories(list) {
    if (!Array.isArray(list) || list.length !== 3) {
      throw new Error("قائمة القصص غير مكتملة.");
    }

    const ids = new Set();

    list.forEach(function (story) {
      if (!story.id || ids.has(story.id)) {
        throw new Error("يوجد معرف قصة مفقود أو مكرر.");
      }

      ids.add(story.id);

      if (
        !story.title ||
        !story.description ||
        !story.cover ||
        !story.author ||
        !Array.isArray(story.chapters) ||
        story.chapters.length < 1
      ) {
        throw new Error("بيانات القصة غير مكتملة: " + story.id);
      }

      story.chapters.forEach(function (chapter) {
        if (
          !chapter.title ||
          !Array.isArray(chapter.paragraphs) ||
          chapter.paragraphs.length < 1 ||
          chapter.paragraphs.some(function (paragraph) {
            return typeof paragraph !== "string" || !paragraph.trim();
          })
        ) {
          throw new Error("فصل غير مكتمل في القصة: " + story.id);
        }
      });
    });
  }

  validateStories(stories);

  const api = {
    getAll: function () {
      return stories.slice();
    },

    getById: function (id) {
      return stories.find(function (story) {
        return story.id === String(id);
      }) || null;
    },

    getByCategory: function (category) {
      if (!category || category === "all") {
        return stories.slice();
      }

      return stories.filter(function (story) {
        return story.category === category;
      });
    },

    search: function (query) {
      const term = String(query || "").trim().toLowerCase();

      if (!term) {
        return stories.slice();
      }

      return stories.filter(function (story) {
        const searchable = [
          story.title,
          story.description,
          story.categoryLabel,
          story.author,
          ...(story.tags || [])
        ].join(" ").toLowerCase();

        return searchable.includes(term);
      });
    },

    getFeatured: function (count) {
      const limit = Number(count) > 0 ? Number(count) : stories.length;

      return stories.filter(function (story) {
        return story.featured;
      }).slice(0, limit);
    },

    getCount: function () {
      return stories.length;
    }
  };

  if (typeof window !== "undefined") {
    window.HANOON_STORIES = stories;
    window.HANOON_STORIES_API = api;

    window.dispatchEvent(new CustomEvent("hanoon:stories-ready", {
      detail: { count: stories.length }
    }));
  }
